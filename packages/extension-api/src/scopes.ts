/**
 * Domain scopes (ADR §5.2).
 *
 * Scopes are the only state an extension sees. Core components provide them
 * at natural boundaries (a fixture row provides `fixture`, a channel control
 * provides `channel` + `signature`, …); every slot inherits all scopes of its
 * ancestors. Views are readonly projections — writes go through commands.
 *
 * The set of scope names is part of the versioned API contract; extensions
 * MUST NOT add new names.
 */
import type { DeepReadonly, ShallowRef } from 'vue';
import type {
  BlendMode,
  ChannelRole,
  ChannelType,
  EffectDirection,
  FixtureId,
  Json,
  SceneNodeId,
  Signature,
  SpeedConfig,
  Vec2,
} from './model';
import type { ParamValue } from './params';

/** A project dependency on an extension (ADR D20). */
export interface ProjectRequirement {
  /** Extension id. */
  id: string;
  /** Semver range, e.g. `'^1.2'`. */
  version: string;
}

/** Global project information. Provided at the app root. */
export interface ProjectInfo {
  /** Project id, or `null` for an unsaved/local project. */
  id: string | null;
  /** Display name. */
  name: string;
  /** Current tempo in beats per minute. */
  bpm: number;
  /** Extensions this project depends on. */
  requires: ProjectRequirement[];
  /** Every fixture in scene order (for pickers; use `getFixture` for details). */
  fixtures: FixtureSummary[];
}

/** Light entry of the project's fixture list. */
export interface FixtureSummary {
  id: FixtureId;
  name: string;
  /** 1-based absolute DMX start address. */
  startAddress: number;
  channelCount: number;
  /** Kind id for kind fixtures. */
  kindId?: string;
}

/** Current selection. Provided at the app root. */
export interface SelectionInfo {
  /** Ids of all selected fixtures (groups expanded to their fixtures). */
  fixtureIds: FixtureId[];
  /** Ids of the selected scene nodes (fixtures and groups, not expanded). */
  nodeIds: SceneNodeId[];
}

/** Which main view is active. */
export type ViewportMode = '2d' | '3d' | 'live' | 'design' | 'fixture-editor';

/** Current viewport. Provided at the app root. */
export interface ViewportInfo {
  mode: ViewportMode;
}

/** A single OFL capability range of a channel. */
export interface CapabilityView {
  /** Inclusive 8-bit DMX bounds. */
  dmxRange: [number, number];
  /** OFL capability type, e.g. `'WheelSlot'`, `'ShutterStrobe'`. */
  type: string;
  /** Human-readable description. */
  comment?: string;
}

/** Readonly view of one channel of a fixture. */
export interface ChannelView {
  /** Owning fixture. */
  fixtureId: FixtureId;
  /** Index of the channel in the fixture's channel list. */
  index: number;
  type: ChannelType;
  role: ChannelRole;
  /** Name from the fixture definition, e.g. `'Shutter'`. */
  name?: string;
  /** Offset from the fixture start address (0-based). */
  addressOffset: number;
  /** Absolute 1-based DMX address across all universes. */
  dmxAddress: number;
  /** Bytes spanned: 1 = 8-bit, 2 = 16-bit, 3 = 24-bit. */
  resolution: 1 | 2 | 3;
  /** Offsets of fine/ultra-fine bytes, if `resolution > 1`. */
  fineAddressOffsets: number[];
  /** True if this entry is the fine/ultra-fine byte of another channel. */
  isFine: boolean;
  /** Lower DMX bound (0–255) the output is remapped into. */
  rangeMin: number;
  /** Upper DMX bound (0–255) the output is remapped into. */
  rangeMax: number;
  /** Default DMX value (0–255). */
  defaultValue: number;
  /** Peak hue as hex string for color/dimmer channels. */
  colorValue: string;
  /** Beam/head this channel controls (multi-head fixtures). */
  beamId?: string;
  /** Programmed static value (0–255) of the active chaser step. */
  value: number;
  /** OFL capabilities, if known. */
  capabilities?: CapabilityView[];
}

/** One beam/head of a fixture in fixture-local normalized coordinates. */
export interface BeamView {
  id: string;
  x: number;
  y: number;
  z: number;
}

/** Reference to the fixture kind that generated a fixture (ADR §5.6). */
export interface FixtureKindRef {
  /** Kind id, e.g. `'neopixel-strip'`. */
  id: string;
  /** Semver of the config format. */
  version: string;
  /** Kind-specific configuration. */
  config: Json;
}

/** Readonly view of one fixture. */
export interface FixtureView {
  id: FixtureId;
  name: string;
  /** 1-based absolute DMX start address. */
  startAddress: number;
  /** 1-based universe number. */
  universe: number;
  /** 1-based address inside the universe. */
  localAddress: number;
  /** Position in normalized world space (0–1). */
  position: Vec2;
  /** Size in normalized world space. */
  size: Vec2;
  /** Rotation in degrees. */
  rotation: number;
  /** Height above floor (normalized like x/y). */
  positionZ: number;
  manufacturer: string;
  fixtureType: string;
  /** OFL key (`manufacturer/fixture`) if created from the library. */
  oflKey?: string;
  channels: ChannelView[];
  beams: BeamView[];
  /** Kind reference if generated by a fixture kind. */
  kind?: FixtureKindRef;
  /** Namespaced extension data: `extensionData[extensionId][key]`. */
  extensionData?: Record<string, Record<string, Json>>;
}

/** A reference to one concrete channel. */
export interface ChannelRef {
  /** Index into the fixture's channel list. */
  channelIndex: number;
  type: ChannelType;
}

/**
 * A signature-typed control target: the set of channels that together form
 * one signature value (e.g. RED+GREEN+BLUE for `rgb`, PAN+TILT for `panTilt`).
 */
export interface SignatureTarget {
  signature: Signature;
  fixtureId: FixtureId;
  /** Channels in signature component order. */
  channelRefs: ChannelRef[];
}

/** Readonly view of a modifier instance (ADR §6.3). */
export interface ModifierInstanceView {
  id: string;
  /** Content-plugin hash (`'sha256:…'`); built-ins too. */
  plugin: string;
  /** Display name. */
  name: string;
  signature: Signature;
  /** For `scalar`: which channel types are targeted. */
  targetChannels?: ChannelType[];
  /** Restricted fixtures; `undefined` = all. */
  targetFixtureIds?: FixtureId[];
  blendMode: BlendMode;
  /** 0–1. */
  strength: number;
  speed: SpeedConfig;
  direction: EffectDirection;
  originX: number;
  originY: number;
  angle: number;
  fanning: number;
  reverse: boolean;
  params: Record<string, ParamValue>;
}

/** Readonly view of a preset. */
export interface PresetView {
  id: string;
  name: string;
  /** `'normal' | 'flash' | 'overwrite'`. */
  type: string;
  /** Fixtures touched by the preset. */
  fixtureIds: FixtureId[];
}

/** Readonly view of a live widget. */
export interface LiveWidgetView {
  id: string;
  /** Widget type, e.g. `'slider'` or `'<extensionId>/<name>'`. */
  type: string;
  gridX: number;
  gridY: number;
  gridW: number;
  gridH: number;
  label?: string;
  color?: string;
  /** Mapping record (shape depends on `mapping.type`). */
  mapping: Record<string, Json>;
  /** Namespaced extension data. */
  extensionData?: Record<string, Record<string, Json>>;
}

/** Readonly view of a live page. */
export interface LivePageView {
  id: string;
  name: string;
  columns: number;
  widgetIds: string[];
}

/**
 * All scope names and their value types. Part of the versioned API contract.
 */
export interface ScopeMap {
  /** Global: id, name, bpm, requires. */
  project: ProjectInfo;
  /** Global: selected fixture ids and scene node ids. */
  selection: SelectionInfo;
  /** Global-ish: which main view is active. */
  viewport: ViewportInfo;
  /** One fixture (fixture rows, property sidebar with single selection). */
  fixture: FixtureView;
  /** One channel (channel controls). */
  channel: ChannelView;
  /** The signature target of a control. */
  signature: SignatureTarget;
  /** One modifier instance (modifier cards). */
  modifier: ModifierInstanceView;
  /** One preset. */
  preset: PresetView;
  /** One live widget. */
  liveWidget: LiveWidgetView;
  /** One live page. */
  livePage: LivePageView;
}

/** Name of a scope. */
export type ScopeName = keyof ScopeMap;

/** All scope names, in a stable order. */
export const SCOPE_NAMES: readonly ScopeName[] = [
  'project',
  'selection',
  'viewport',
  'fixture',
  'channel',
  'signature',
  'modifier',
  'preset',
  'liveWidget',
  'livePage',
];

/** The readonly reactive handle an extension receives for a scope. */
export type ScopeRef<K extends ScopeName> = Readonly<ShallowRef<DeepReadonly<ScopeMap[K]> | undefined>>;

/** Unwrapped readonly scope values, as passed to `when` predicates. */
export type ScopeSnapshot = { readonly [K in ScopeName]?: DeepReadonly<ScopeMap[K]> };
