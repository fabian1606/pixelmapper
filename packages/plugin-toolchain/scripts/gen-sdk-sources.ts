/**
 * Embeds the AssemblyScript SDK (`packages/plugin-sdk/assembly/*.ts`) into
 * `src/sdk-sources.generated.ts`, so the compiler can resolve
 * `@pixelmapper/plugin-sdk` from memory in Bun and in the browser alike.
 *
 * Run: `bun run gen:sdk` (also run by scripts/build-plugins.ts).
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const here = resolve(import.meta.dir, '..');
const sdkDir = resolve(here, '../plugin-sdk/assembly');
const out = join(here, 'src/sdk-sources.generated.ts');

const files = (await readdir(sdkDir)).filter(f => f.endsWith('.ts')).sort();
const entries: string[] = [];
for (const f of files) {
  const src = await readFile(join(sdkDir, f), 'utf8');
  entries.push(`  ${JSON.stringify(f)}: ${JSON.stringify(src)},`);
}

const code = `/**
 * GENERATED by scripts/gen-sdk-sources.ts — do not edit.
 * AssemblyScript SDK sources (packages/plugin-sdk/assembly), keyed by file name.
 */
export const SDK_SOURCES: Readonly<Record<string, string>> = {
${entries.join('\n')}
};
`;

const previous = await readFile(out, 'utf8').catch(() => '');
if (previous !== code) {
  await writeFile(out, code);
  console.log(`[gen-sdk] wrote ${files.length} SDK file(s)`);
}
